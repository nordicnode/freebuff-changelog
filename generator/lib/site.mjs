async function write (dist, p, html) { await writeText(`${dist.replace(/\/$/, '')}/${p}`, html) }

export async function buildSite ({ changelog, openPrs, dist }) {
  const entries = [...changelog.entries].reverse() // newest first
  const byDay = groupByDay(entries)
  const major = entries.filter(e => e.significance === 'major')
  const modelEntries = entries.filter(e => e.modelChanges)
  const releases = entries.filter(e => e.version)
  const first = entries.at(-1), last = entries[0]
  const generated = changelog.generatedAt

  // ----- index: newest days worth of entries
  const NEW_WINDOW = 90
  const idx = []
  let n = 0
  for (const d of byDay) { if (n >= NEW_WINDOW) break; idx.push(d); n += d.entries.length }
  const hero = `
<section class="hero"><h1>${SITE.name}</h1><p>${SITE.tagline}</p>
<div class="stats">
<div class="stat"><b>${entries.length.toLocaleString()}</b> changes tracked</div>
<div class="stat"><b>${releases.length.toLocaleString()}</b> releases</div>
<div class="stat"><b>${modelEntries.length}</b> model-lineup changes</div>
<div class="stat"><b>${changelog.counts?.commitsScanned || entries.length}</b> upstream commits analyzed</div>
</div>
<p class="muted">Covering ${esc(first.day)} → ${esc(last.day)} (UTC). Latest snapshot analyzed: <code>${esc((changelog.headSha || '').slice(0, 12))}</code> · updated ${esc(fmtDateHuman(generated))}.</p>
</section>`
  const daysHtml = idx.map(d =>
    `<section class="day" id="${d.day}"><h2><time>${esc(fmtDateHuman(d.day))}</time><span class="daysub">${d.entries.length} change${d.entries.length === 1 ? '' : 's'}</span></h2>
${d.entries.map(entryCard).join('\n')}</section>`).join('')
  await write(dist, 'index.html', layout({ title: 'Home', path: '/', body: hero + daysHtml +
    `<div class="pager"><a href="/archive/">Full archive →</a><a href="/feed.xml">RSS (major & notable)</a></div>` }))

  // ----- per-day pages
  for (const d of byDay) {
    await write(dist, `day/${d.day}/index.html`, layout({
      title: fmtDateHuman(d.day), path: `/day/${d.day}/`,
      desc: `${d.entries.length} Freebuff changes on ${d.day}`,
      body: `<section class="hero"><h1><time>${esc(fmtDateHuman(d.day))}</time></h1><p>${d.entries.length} change${d.entries.length === 1 ? '' : 's'} pushed to the public repo this day.</p></section>` +
        `<section class="day">${d.entries.map(entryCard).join('\n')}</section>` +
        `<p><a href="/">← Latest</a> · <a href="/archive/">Archive</a></p>`
    }))
  }

  // ----- release pages
  const verMap = new Map()
  for (const e of releases) verMap.set(e.version, e)
  const vers = [...verMap.values()]
  vers.sort((a, b) => a.date < b.date ? -1 : 1)
  for (let i = 0; i < vers.length; i++) {
    const rel = vers[i]
    const lo = i > 0 ? vers[i - 1].date : '0000'
    const mine = entries.filter(e => e.date > lo && e.date <= rel.date && e.sha !== rel.sha)
    await write(dist, `release/${rel.version}/index.html`, layout({
      title: `Release ${rel.version}`, path: `/release/${rel.version}/`,
      desc: `Freebuff v${rel.version} — ${mine.length} changes since the previous release.`,
      body: `<section class="hero"><h1>Freebuff v${esc(rel.version)}</h1><p>Released ${esc(fmtDateHuman(rel.date))} UTC · <code>${rel.sha.slice(0, 12)}</code> · ${mine.length} changes since the previous release.</p></section>` +
        `<section class="day">${[rel, ...mine].map(entryCard).join('\n')}</section><p><a href="/archive/#releases">← All releases</a></p>`
    }))
  }

  // ----- archive (all days + releases + categories)
  const cats = new Map()
  for (const e of entries) cats.set(e.category, (cats.get(e.category) || 0) + 1)
  const catTiles = [...cats.entries()].sort((a, b) => b[1] - a[1]).map(([c, k]) =>
    `<div class="tile"><b>${esc(c)}</b><span>${k} changes</span></div>`).join('')
  const dayLinks = byDay.map(d => `<li><a href="/day/${d.day}/">${esc(d.day)}</a> <span class="muted">${d.entries.length}</span></li>`).join('')
  const relLinks = [...vers].reverse().map(v => `<li><a href="/release/${v.version}/">${esc(v.version)}</a> <span class="muted">${esc(v.date.slice(0, 10))}</span></li>`).join('')
  await write(dist, 'archive/index.html', layout({
    title: 'Archive', path: '/archive/',
    body: `<section class="hero"><h1>Archive</h1><p>Every ${entries.length} tracked changes, ${byDay.length} active days, ${vers.length} releases.</p>
<div class="grid">${catTiles}</div></section>
<h2 id="releases" class="day" style="border-bottom:1px solid var(--line)">Releases</h2><ul>${relLinks}</ul>
<h2 class="day" style="border-bottom:1px solid var(--line)">Days</h2><ul>${dayLinks}</ul>`
  }))

  // ----- search (the only page with JS: tiny client filter over JSON index)
  const idxJson = entries.map(e => ({
    d: e.day, t: (e.ai?.title || e.title || '').slice(0, 90), c: e.category, s: e.sha.slice(0, 12), a: e.significance,
    u: `/day/${e.day}/#${e.sha.slice(0, 12)}`
  }))
  await write(dist, 'search-index.json', JSON.stringify(idxJson))
  await write(dist, 'search/index.html', layout({
    title: 'Search', path: '/search/',
    body: `<section class="hero"><h1>Search ${entries.length} changes</h1><p>Model names, files, commands, releases.</p></section>
<input id="q" type="search" placeholder="e.g. muse spark, slash command, runner…" autocomplete="off">
<div id="hits"></div>
<script>
fetch('/search-index.json').then(r=>r.json()).then(ix=>{let t;const q=document.getElementById('q'),h=document.getElementById('hits');
const go=()=>{const v=q.value.trim().toLowerCase();if(!v){h.innerHTML='';return}
const w=v.split(/\\s+/);const hits=ix.filter(e=>{const s=(e.t+' '+e.c).toLowerCase();return w.every(x=>s.includes(x))}).slice(0,200);
h.innerHTML=hits.map(e=>'<article class="entry"><h3><a href="'+e.u+'">'+e.t+'</a></h3><div class="badges"><span class="badge">'+e.c+'</span><span class="badge">'+e.a+'</span><span class="badge">'+e.d+'</span></div></article>').join('')||'<p class="muted">No matches.</p>'};
q.addEventListener('input',()=>{clearTimeout(t);t=setTimeout(go,120)})})
</script>`
  }))

  // ----- about
  await write(dist, 'about/index.html', layout({
    title: 'About', path: '/about/',
    body: `<section class="hero"><h1>About this changelog</h1>
<div class="summary" style="max-width:70ch">
<p><strong>Why:</strong> Freebuff's public repo is a mirror. A bot pushes "Sync public snapshot" commits from the private repo, and the commit messages say nothing — so the community can't see what changed.</p>
<p><strong>How:</strong> this site analyzes the <em>diff</em> behind every public commit (${entries.length.toLocaleString()} tracked changes from ${esc(changelog.counts?.commitsScanned || '?').toLocaleString()} analyzed commits). Each sync snapshot's diff is usually one focused change, so per-commit entries are highly accurate. A rule-based extractor detects model-catalog edits in the README table, CLI version bumps, new/removed slash commands, added/deleted/renamed files, and informative inline comments. An optional AI pass (cached, one call per commit, from the exact diff text) can rewrite summaries — never inventing beyond the diff.</p>
<p><strong>Updates:</strong> a GitHub Action reruns the analyzer hourly; Cloudflare Pages redeploys automatically. This page you are reading is a pre-rendered static file with zero client JavaScript (except /search), one inline stylesheet, system fonts, and edge caching.</p>
<p><strong>Limitations:</strong> multiple private commits can sometimes land in one public snapshot; internal-only changes are labeled as such. Commit and diff links give you ground truth.</p>
</div></section>`
  }))

  // ----- open PRs page (community activity ahead of merges)
  if (openPrs?.length) {
    const rows = openPrs.map(p => `<li><a href="${esc(p.url)}" rel="noopener">${esc(p.title)}</a>
<span class="muted">#${p.number} by ${esc(p.author)} · ${esc(p.updated.slice(0, 10))} · +${p.additions}/−${p.deletions}${p.draft ? ' · draft' : ''}</span></li>`).join('')
    await write(dist, 'in-flight/index.html', layout({
      title: 'In flight', path: '/in-flight/',
      body: `<section class="hero"><h1>In flight</h1><p>Open community PRs on the Freebuff repo (merged PRs appear here in the changelog the moment they land). Updated ${esc(fmtDateHuman(generated))}.</p></section><ul>${rows}</ul>`
    }))
  }

  // ----- feeds / api
  const feedEntries = entries.filter(e => e.significance !== 'minor').slice(0, 60)
  const items = feedEntries.map(e => {
    const title = e.ai?.title || e.title || deriveTitleSafe(e)
    return `<item><title>${esc(title)}</title><link>${SITE.url}/day/${e.day}/#${e.sha.slice(0, 12)}</link>
<guid isPermaLink="false">${esc(e.sha)}</guid><pubDate>${new Date(e.date).toUTCString()}</pubDate>
<description>${esc(title)} — ${esc((e.ai?.summary || e.summary).replace(/[*`#]/g, ''))}</description></item>`
  }).join('')
  await write(dist, 'feed.xml',
    `<?xml version="1.0" encoding="UTF-8"?><rss version="2.0"><channel><title>${SITE.name} (unofficial)</title>
<link>${SITE.url}</link><description>${esc(SITE.desc)}</description><language>en</language>${items}</channel></rss>`)

  await write(dist, 'changelog.json', JSON.stringify(changelog))
  await write(dist, 'api/entries.json', JSON.stringify({ generatedAt: generated, head: changelog.headSha, total: entries.length, latest: entries.slice(0, 60) }))

  // ----- sitemap / robots / headers / 404
  const urls = ['/']
  for (const d of byDay) urls.push(`/day/${d.day}/`)
  for (const v of vers) urls.push(`/release/${v.version}/`)
  urls.push('/archive/', '/search/', '/about/', '/in-flight/')
  await write(dist, 'sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${urls.map(u => `<url><loc>${SITE.url}${u}</loc></url>`).join('')}</urlset>`)
  await write(dist, 'robots.txt', `User-agent: *\nAllow: /\nSitemap: ${SITE.url}/sitemap.xml\n`)
  await write(dist, '_headers', `/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
/index.html
  Cache-Control: public, max-age=300
/changelog.json
  Cache-Control: public, max-age=300
/search-index.json
  Cache-Control: public, max-age=3600
/feed.xml
  Cache-Control: public, max-age=600
/sitemap.xml
  Cache-Control: public, max-age=86400
/day/
  Cache-Control: public, max-age=86400
/release/
  Cache-Control: public, max-age=86400
`)
  await write(dist, '404.html', layout({ title: 'Not found', path: '/404', body: '<h1>404 — nothing shipped here… yet.</h1><p><a href="/">← Back to the changelog</a></p>' }))

  return { entries: entries.length, days: byDay.length, releases: vers.length }
}
