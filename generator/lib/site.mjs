  const trafficUniques = traffic?.uniques ?? 0
  activeTraffic = { count: trafficCount, uniques: trafficUniques }
  const entries = [...changelog.entries].reverse() // newest first
  const byDay = groupByDay(entries)
  // "Related" is a reading aid for real changes: churn rows must neither appear
  // in it nor link out of it.
  const relatedIdx = buildRelatedIndex(entries.filter(e => !e.noise))
  // Same-day, same-code clusters. Derived per build from the entries in hand, so a
  // note appears the moment the second half of a story lands -- no cache, no
  // version and nothing to merge (see story.mjs).
  const storyIdx = buildStoryIndex(entries)
  // Which release first carried each commit (per track), from the bumps in hand.
  const shipped = computeShippedIn(changelog.entries)
  const cardOpts = (e, extra = {}) => ({ storyNotes: storyIdx.notes.get(e.sha), shipped, ...extra })
  const modelEntries = entries.filter(e => e.modelChanges)
  const releases = entries.filter(e => e.version)
  const first = entries.at(-1), last = entries[0]
  const generated = changelog.generatedAt
  const scannedCount = changelog.counts?.commitsScanned || entries.length
  // Two different claims: commits received vs changes worth reading. Churn rows
  // are listed so nothing is hidden, but they must not inflate the headline.
  const meaningful = entries.filter(e => !e.noise)
  const churnCount = entries.length - meaningful.length
  const churnNote = churnCount ? ` &middot; ${churnCount.toLocaleString()} churn` : ''
  // All-time browse index, computed up front because the front-page chips need
  // each category's *total* next to its count in this window. "CLI 27" on a page
  // holding 91 changes is a fact about this page, not about CLI: 1,413 CLI
  // changes exist. Both numbers belong on screen, not one pretending to be the
  // other.
  const catLists = new Map()
  for (const e of entries) {
    if (e.noise) continue
    if (!catLists.has(e.category)) catLists.set(e.category, [])
    catLists.get(e.category).push(e)
  }
  const churnList = entries.filter(e => e.noise)
  const browseList = [...catLists.entries()].map(([label, list]) => ({ label, slug: categorySlug(label), list, churn: false }))
  if (churnList.length) browseList.push({ label: 'Churn', slug: 'churn', list: churnList, churn: true })
  browseList.sort((a, b) => b.list.length - a.list.length || a.label.localeCompare(b.label))
  const browseBySlug = new Map(browseList.map(b => [b.slug, b]))
  // How long the data is allowed to sit before the sync loop re-analyzes. The
  // [fresh]/[stale] badge has to be stated in these terms: it used to tick to the
  // top of the next hour, describing a schedule that no longer owns freshness.
  const syncBudgetMin = Math.round(syncStaleMs() / 60000)

  // ----- the timeline: one day per page
  // `/` is the newest day and `/day/<date>/` is every older one, rendered by the
  // same code. Two page families for the same list is how they start to disagree
  // about what a row means; and because the page *is* a date, the heading on
  // screen, the URL, the pager and a shared link can never drift apart.
  const pageCount = byDay.length
  const timelineHref = (i) => (i === 0 ? '/' : `/day/${byDay[i].day}/`)
  const dayOptions = byDay.map(d => `<option value="/day/${d.day}/">${esc(fmtDateHuman(d.day))} (${d.entries.filter(e => !e.noise).length})</option>`).join('')
  // One select per page, not two: 721 options is ~42 KB of markup, and the second
  // copy used to be 55% of the front page's bytes. The bottom bar points at the
  // top one instead, which also says where the control is.
  const dayJump = (current, withId) => `<form class="day-jump"${withId ? ' id="day-jump"' : ''} action="/day/${current}/" method="get" onsubmit="location.href=this.d.value;return false"><label>JUMP:<select name="d" onchange="if(this.value)location.href=this.value"><option value="">--pick a date--</option>${dayOptions}</select></label></form>`
  const jumpLink = '<a href="#day-jump">[jump to a date &uarr;]</a>'

  // Chips are per page: each one counts the rows it can actually hide *here*.
  const chipHtml = (slug, label, n, active, extraClass) => {
    const b = browseBySlug.get(slug)
    const total = b ? b.list.length : meaningful.length
    const href = b ? `/changes/${b.slug}/` : '/archive/#categories'
    return `  <button type="button" class="chip${active ? ' active' : ''}${extraClass}" data-filter="${esc(slug)}" data-label="${esc(label)}" data-total="${total}" data-href="${esc(href)}" aria-pressed="${active ? 'true' : 'false'}">${esc(label)}<span class="chip-n">${n.toLocaleString()}</span></button>`
  }

  // Walking the timeline is walking dates: older to the left (the site's existing
  // convention), newer to the right. The jump select lives in the bar under the
