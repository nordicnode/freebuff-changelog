// Discord's markdown is a small dialect: **bold**, ### headings, > quotes, `- `
// lists and ``` fenced blocks. No tables, and no alignment outside a code block.
// It also does not hard-wrap, so one long paragraph arrives as an unreadable wall.
//
// The message is deliberately minimal: a `### title` header with the date, an
// optional related-context quote block, and one plain-English paragraph (the
// plain-English line, falling back to the summary). Earlier revisions also sent
// per-sentence summary lines, a model-change list and a fenced details block;
// the broadcast tests pin this shape, because an announcement has to read as
// one message wherever it lands. No links of any kind -- the commit is
// identified by its SHA, and the message stands on its own.
const DC_LIMIT = 2000

// Zero-width space. Invisible in the paste, fatal to Discord's URL matcher, so a
// mentioned endpoint stays readable text instead of becoming a link or an embed.
const ZWSP = String.fromCharCode(0x200b)

// Escape outside `code spans` only: inside one, a literal underscore is already
// safe, and escaping it there would show the backslash.
function dcEsc (s) {
  let raw = String(s)
  // Backticks first, because they decide whether anything else is read as text:
  // an odd count leaves an inline span open for the rest of the message, and a run
  // of three opens a fence -- which some prompt-text summaries contain. Escaping
  // them costs the styling and keeps the message readable; leaving them would do
  // the opposite. An even count means the pairs are the intended code spans.
  const odd = ((raw.match(/`/g) || []).length) % 2 === 1
  if (odd) raw = raw.replace(/`/g, '\\`')
  else raw = raw.replace(/`{3,}/g, run => run.replace(/`/g, '\\`'))
  const segs = odd ? [raw] : raw.split(/(`[^`]*`)/)
  // The stored summaries use **bold** deliberately, so a balanced pair passes
  // through. A *loner* does not: README bullets arrive as `text.** More text`,
  // one pair with nothing to close against, and Discord would bold the rest of the
  // message from there. Parity is checked on pairs and on leftover single stars
  // separately -- two stars is a pair, not two italics markers.
  //
  // An unbalanced line has its markers *dropped*, not backslash-escaped: escaping
  // would print `research.\*\* No subscription` in the source and render a stray
  // `**` in the message, and either way the reader sees debris that meant nothing.
  // Underscores are the opposite case -- they are usually part of a real path or
  // identifier -- so those are escaped rather than removed.
  let pairs = 0, singles = 0
  for (let i = 0; i < segs.length; i += 2) {
    const t = segs[i]
    const n = (t.match(/\*/g) || []).length
    pairs += Math.floor(n / 2)
    singles += n % 2
  }
  const dropStars = pairs % 2 === 1 || singles > 0
  return segs.map((part, i) => {
    if (i % 2) return part
    let out = part.replace(/_/g, '\\_').replace(/\|\|/g, '\\|\\|')
    // Nothing in the paste may be clickable. But seventeen summaries *mention* an
    // endpoint as the subject of the commit, and deleting that would delete the
    // change -- so the words stay and the reachability goes: a markdown link
    // collapses to its label, and a zero-width space after the colon stops Discord
    // linkifying or embedding a bare URL. Inside a code span nothing is touched,
    // because Discord does not linkify there and `https://registry.npmjs.org` as
    // monospace text is exactly what the reader needs.
    out = out.replace(/\[([^\]]+)\]\((?:https?:)?\/\/[^)]*\)/g, '$1')
    out = out.replace(/(https?):\/\//g, (m, p) => `${p}:${ZWSP}//`)
    if (dropStars) out = out.replace(/\*/g, '')
    return out
  }).join('')
}

export function discordText (e, opts = {}) {
  const title = e.ai?.title || e.title || deriveTitleSafe(e)
  const dateStr = fmtDateHuman(e.day || e.date)
  const plain = String(e.eli5?.text || e.ai?.summary || e.summary || '').replace(/\s+/g, ' ').trim()

  const parts = [`### ${dcEsc(title)}\n${dateStr}`]
  if (opts.storyNotes?.length) {
    parts.push(`> **Related access context**\n> ${opts.storyNotes.map(n => dcEsc(clipText(n.text, 600))).join('\n> ')}`)
  }
  if (plain) {
    parts.push(dcEsc(plain))
  }

  let text = parts.join('\n\n')
  if (text.length > DC_LIMIT && plain) {
    const overhead = text.length - plain.length
    const room = DC_LIMIT - overhead - 4
    const clipped = clipText(plain, Math.max(0, room))
    parts[parts.length - 1] = dcEsc(clipped)
    text = parts.join('\n\n')
  }
  return text.length > DC_LIMIT ? text.slice(0, DC_LIMIT - 1) + '…' : text
}

// Search ranking (mirrored client-side): title hits beat category hits,
// significance boosts, recency breaks ties. Exported for unit tests.
export function scoreHit (title, cat, sig, day, words, eli5 = '', extra = '') {
  const t = title.toLowerCase(), c = cat.toLowerCase(), el = (eli5 || '').toLowerCase(), ex = (extra || '').toLowerCase()
  let s = 0
  for (const w of words) {
    // Weights mirror the client matcher in the /search/ page exactly (title
    // 4/3 by length, plain-English 2, category/extra 1): the two used to drift,
    // so a row could rank differently here than in the browser.
    if (t.includes(w)) s += w.length > 4 ? 4 : 3
    else if (el.includes(w)) s += 2
    else if (c.includes(w)) s += 1
    // File paths and the evidence citation: what a developer searches by.
    else if (ex.includes(w)) s += 1
    else return -1
  }
  if (sig === 'major') s += 2
  else if (sig === 'notable') s += 1
  return s
}

// Impact filtering is a minimum, not an equality: the "notable + major" filter
// used to be `a !== sig`, so choosing it silently dropped every major row. The
// client matcher mirrors this rank rule.
export const IMPACT_RANK = { minor: 0, notable: 1, major: 2 }
export function impactAllows (rowSig, filterSig) {
  if (!filterSig) return true
  return (IMPACT_RANK[rowSig] ?? 0) >= (IMPACT_RANK[filterSig] ?? 0)
}

// Search query grammar, parsed identically by this function (unit-tested) and
// the /search/ page's client mirror. Everyday typing keeps working exactly as
// it always did (words are substrings); the syntax layers on top:
//   cat:cli sig:>=notable aud:end-users   field filters (sig takes >= <= > < =)
//   is:release|breaking|security|model|pr|edited|eli5|unverified
//   "page url"                            phrase (matches as a substring)
//   -chore                                exclude matches
// Unknown `key:` forms fall through as plain words, so pasted identifiers and
// file paths are never eaten by the parser.
export function parseQuery (input) {
  const words = [], phrases = [], neg = []
  const filters = {}
  const tokens = String(input || '').match(/-?(?:"[^"]*"|\S+)/g) || []
  for (let tok of tokens) {
    let banned = false
    if (tok.startsWith('-') && tok.length > 1) { banned = true; tok = tok.slice(1) }
    if (tok.startsWith('"')) {
      const phrase = tok.replace(/"/g, '').trim().toLowerCase()
      if (phrase) (banned ? neg : phrases).push(phrase)
      continue
    }
    const m = /^([a-z]+):(.+)$/i.exec(tok)
    if (m) {
      const key = m[1].toLowerCase(), val = m[2].toLowerCase()
      if (!banned && key === 'cat' && val) { filters.cat = val; continue }
      if (!banned && key === 'aud' && val) { filters.aud = val; continue }
      if (!banned && key === 'sig' && val) {
        const c = /^(>=|<=|>|<|=)?([a-z]+)$/.exec(val)
        if (c && IMPACT_RANK[c[2]] !== undefined) { filters.sig = { op: c[1] || '=', value: c[2] }; continue }
      }
      if (!banned && key === 'is' && val) { (filters.is || (filters.is = [])).push(val); continue }
    }
    // Not a recognized form: an ordinary word (identifiers, paths, versions).
    if (tok) (banned ? neg : words).push(tok.toLowerCase())
  }
  return { words, phrases, neg, filters }
}

