let activeEntryIdx = -1;
function getVisibleEntries() {
  return Array.from(document.querySelectorAll('details.entry:not([hidden])'));
}
function setActiveEntry(idx) {
  const entries = getVisibleEntries();
  if (!entries.length) return;
  if (idx < 0) idx = 0;
  if (idx >= entries.length) idx = entries.length - 1;
  activeEntryIdx = idx;
  entries.forEach((e, i) => e.classList.toggle('kb-active', i === idx));
  scrollToEl(entries[idx], 'nearest');
}

document.addEventListener('keydown', (e) => {
  const tag = document.activeElement ? document.activeElement.tagName : '';
  const isInput = ['INPUT', 'TEXTAREA', 'SELECT'].includes(tag);

  if (e.key === 'Escape') {
    const modal = document.getElementById('kb-modal');
    if (modal && !modal.hidden) { setKbModal(false); return; }
    if (isInput) { document.activeElement.blur(); return; }
  }

  // With the shortcuts dialog open, Tab walks the dialog only -- focus must not
  // leak to the page behind an aria-modal="true" box.
  if (e.key === 'Tab') {
    const modal = document.getElementById('kb-modal');
    if (modal && !modal.hidden) {
      const items = modal.querySelectorAll('button, a[href]');
      if (items.length) {
        const first = items[0], last = items[items.length - 1];
        if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
        else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
      }
      return;
    }
  }

  if (isInput) return;
  // Enter and Space belong to whatever control has focus: a keyboard reader who
  // used j/k once and then Tabs to a link must be able to activate that link
  // without the marked entry toggling in the same keystroke.
  if ((tag === 'A' || tag === 'BUTTON' || tag === 'SUMMARY') && (e.key === 'Enter' || e.key === ' ')) return;
  if (e.ctrlKey || e.metaKey || e.altKey) return;

  if (e.key === '?') {
    e.preventDefault();
    const modal = document.getElementById('kb-modal');
    if (modal) setKbModal(modal.hidden);
    return;
  }

  if (e.key === '/') {
    e.preventDefault();
    const q = document.getElementById('q');
    if (q) { q.focus(); q.select(); }
    else { window.location.href = '/search/'; }
    return;
  }

  if (e.key === 'j' || e.key === 'ArrowDown') {
    const entries = getVisibleEntries();
    if (entries.length) {
      e.preventDefault();
      setActiveEntry(activeEntryIdx + 1);
    }
    return;
  }

  if (e.key === 'k' || e.key === 'ArrowUp') {
    const entries = getVisibleEntries();
    if (entries.length) {
      e.preventDefault();
      setActiveEntry(activeEntryIdx - 1);
    }
    return;
  }

  if (e.key === 'o' || e.key === 'Enter') {
    const entries = getVisibleEntries();
    if (entries.length && activeEntryIdx >= 0 && activeEntryIdx < entries.length) {
      e.preventDefault();
      const ent = entries[activeEntryIdx];
      ent.open = !ent.open;
    }
    return;
  }

  if (e.key === 'd') {
    const entries = getVisibleEntries();
    if (entries.length && activeEntryIdx >= 0 && activeEntryIdx < entries.length) {
      const dv = entries[activeEntryIdx].querySelector('.diff-viewer');
      if (dv) {
        e.preventDefault();
        // The diff lives inside the power-user section: opening it reveals the
        // whole details chain so the toggle lands where the reader is looking.
        if (!dv.open) {
          for (let d = dv.parentElement; d; d = d.parentElement) {
            if (d.tagName === 'DETAILS') d.open = true;
          }
        }
        dv.open = !dv.open;
      }
    }
    return;
  }

  if (e.key === 'c') {
    const entries = getVisibleEntries();
    if (entries.length && activeEntryIdx >= 0 && activeEntryIdx < entries.length) {
      const btn = entries[activeEntryIdx].querySelector('.dc-copy');
      if (btn) {
        e.preventDefault();
        btn.click();
      }
    }
    return;
  }

  if (e.key === 'n' || e.key === 'N') {
    const nextLink = document.querySelector('.pager a[rel="' + 'next"]');
    if (nextLink && nextLink.href) { window.location.href = nextLink.href; }
    return;
  }

  if (e.key === 'p' || e.key === 'P') {
    const prevLink = document.querySelector('.pager a[rel="' + 'prev"]');
    if (prevLink && prevLink.href) { window.location.href = prevLink.href; }
    return;
  }
});

