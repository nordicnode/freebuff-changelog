function deriveTitleSafe (e) {
  return (e.summary || '').split(/[.:]/)[0].slice(0, 70) || `${e.category} update`
}

// Search ranking (mirrored client-side): title hits beat category hits,
// significance boosts, recency breaks ties. Exported for unit tests.
export function scoreHit (title, cat, sig, day, words) {
  const t = title.toLowerCase(), c = cat.toLowerCase()
  let s = 0
  for (const w of words) {
    if (t.includes(w)) s += w.length > 4 ? 3 : 2
    else if (c.includes(w)) s += 1
    else return -1
  }
  if (sig === 'major') s += 2
  else if (sig === 'notable') s += 1
  return s
}

export function modelSlug (name) {
  const base = String(name).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'model'
  return base
}

function groupByDay (entries) {
  const out = []
  let cur = null
  for (const e of entries) {
    if (!cur || cur.day !== e.day) { cur = { day: e.day, entries: [] }; out.push(cur) }
    cur.entries.push(e)
  }
  return out
}

// Replay model catalog changes oldest-first: current lineup vs retired.
export function modelTimeline (modelEntries) {
  const chrono = [...modelEntries].sort((a, b) => a.date < b.date ? -1 : a.date > b.date ? 1 : (a.sha < b.sha ? -1 : 1))
  const live = new Set(), retired = new Set()
  for (const e of chrono) {
    for (const a of (e.modelChanges?.added || [])) { live.add(a); retired.delete(a) }
    for (const r of (e.modelChanges?.removed || [])) { live.delete(r); retired.add(r) }
  }
  return { chrono: chrono.reverse(), live: [...live].sort(), retired: [...retired].sort() }
}


