function badges (e) {
  const b = []
  if (e.significance === 'major') b.push('<span class="badge maj">major</span>')
  else if (e.significance === 'notable') b.push('<span class="badge not">notable</span>')
  if (e.modelChanges) b.push('<span class="badge model">model lineup</span>')
  if (e.version) b.push(`<a class="badge ver" href="/release/${e.version}/">v${e.version}</a>`)
  if (e.kind === 'community' && e.pr) b.push(`<span class="badge">PR #${e.pr}</span>`)
  b.push(`<span class="badge">${esc(e.category)}</span>`)
  if (e.ai?.title) b.push('<span class="badge" title="summary AI-assisted from the exact diff">ai</span>')
  return b.join('')
}

function modelDiffLine (e) {
  if (!e.modelChanges) return ''
  const { added = [], removed = [] } = e.modelChanges
  const parts = []
  if (added.length) parts.push(added.map(m => `<span class="modelplus">+${esc(m)}</span>`).join(' '))
  if (removed.length) parts.push(removed.map(m => `<span class="modelminus">−${esc(m)}</span>`).join(' '))
  return `<div class="summary">${parts.join(' → ')}</div>`
}

function fileChips (e) {
  const chips = []
  for (const p of e.files.added.slice(0, 3)) chips.push(`<span class="fchip add">${esc(p)}</span>`)
  for (const p of e.files.removed.slice(0, 3)) chips.push(`<span class="fchip del">${esc(p)}</span>`)
  for (const p of e.files.modified.slice(0, e.files.added.length + e.files.removed.length ? 3 : 5)) chips.push(`<span class="fchip mod">${esc(p)}</span>`)
  const extra = Math.max(0, e.files.meaningful - chips.length)
  if (extra > 0) chips.push(`<span class="fchip">+${extra} more</span>`)
  return chips.length ? `<div class="files">${chips.join('')}</div>` : ''
}

function entryCard (e) {
  const t = fmtDateHuman(e.date)
  const time = e.date.slice(11, 16)
  const anchor = e.sha.slice(0, 12)
  return `<article class="entry ${e.significance}" id="${anchor}">
<h3>${e.ai?.title ? esc(e.ai.title) : esc(e.title || deriveTitleSafe(e))}</h3>
${modelDiffLine(e)}
<div class="badges">${badges(e)}</div>
<div class="summary">${miniMd(e.ai?.summary || e.summary)}</div>
${e.facts?.length ? `<ul class="facts">${e.facts.slice(0, 3).map(f => `<li>${miniMd(f)}</li>`).join('')}</ul>` : ''}
${fileChips(e)}
<div class="metarow"><span>${esc(t)} ${esc(time)} UTC</span>
<span class="diffstat"><b>+${e.stats.additions}</b> / <i>−${e.stats.deletions}</i> · ${e.files.total} files</span>
${e.sourceSha ? `<a href="https://github.com/CodebuffAI/freebuff/commit/${e.sha}" rel="noopener">snapshot ${anchor}</a>` : ''}
${e.pr ? `<a href="${esc(e.prUrl || '')}" rel="noopener">PR #${e.pr}</a>` : ''}
${e.compareUrl ? `<a href="${esc(e.compareUrl)}" rel="noopener">diff</a>` : e.url ? `<a href="${esc(e.url)}" rel="noopener">commit</a>` : ''}
</div></article>`
}

function deriveTitleSafe (e) {
  return (e.summary || '').split(/[.:]/)[0].slice(0, 70) || `${e.category} update`
}

function groupByDay (entries) {
  const out = []
  let cur = null
  for (const e of entries) {
    if (!cur || cur.day !== e.day) { cur = { day: e.day, entries: [] }; out.push(cur) }
    cur.entries.push(e)
  }
  return out
}

