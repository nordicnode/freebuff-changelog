/**
 * Generate GitHub Release formatted markdown for a release version.
 */
export function generateReleaseNotesMarkdown (rel, commits = []) {
  const version = rel?.version ? `v${rel.version}` : 'Release'
  const date = (rel?.date || '').slice(0, 10)
  const lines = [`# Freebuff ${version}${date ? ` (${date})` : ''}`, '']

  const features = []
  const models = []
  const cli = []
  const fixes = []
  const other = []

  for (const e of commits) {
    if (e.sha === rel?.sha) continue
    const title = e.ai?.title || e.title || deriveTitleSafe(e)
    const commitUrl = `https://github.com/CodebuffAI/freebuff/commit/${e.sha}`
    const commitLink = `[\`${e.sha.slice(0, 7)}\`](${commitUrl})`
    const bullet = `- **${title}** ${commitLink}`

    if (e.significance === 'major' || e.category === 'Feature') {
      features.push(bullet)
    } else if (e.category === 'Model Catalog' || e.modelChanges) {
      models.push(bullet)
    } else if (e.category === 'CLI' || e.category === 'Commands' || (e.areas && e.areas.includes('cli'))) {
      cli.push(bullet)
    } else if (e.category === 'Bug Fix' || (e.title && /^(fix|bugfix)\b/i.test(e.title))) {
      fixes.push(bullet)
    } else if (!e.noise) {
      other.push(bullet)
    }
  }

  if (features.length) lines.push('## Features & Highlights', ...features, '')
  if (models.length) lines.push('## Model Catalog Updates', ...models, '')
  if (cli.length) lines.push('## CLI & Commands', ...cli, '')
  if (fixes.length) lines.push('## Bug Fixes & Refactors', ...fixes, '')
  if (other.length) lines.push('## Maintenance & Improvements', ...other, '')

  lines.push('---', '*Generated by [Freebuff Changelog](https://changelog.freebuff.dev)*')
  return lines.join('\n')
}

export function modelSlug (name) {
  const base = String(name).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'model'
  return base
}

function groupByDay (entries) {
  const out = []
  let cur = null
  for (const e of entries) {
    if (!cur || cur.day !== e.day) { cur = { day: e.day, entries: [] }; out.push(cur) }
    cur.entries.push(e)
  }
  return out
}

// Replay model catalog changes oldest-first: current lineup vs retired.
export function modelTimeline (modelEntries) {
  const chrono = [...modelEntries].sort((a, b) => a.date < b.date ? -1 : a.date > b.date ? 1 : (a.sha < b.sha ? -1 : 1))
  const live = new Set(), retired = new Set()
  for (const e of chrono) {
    for (const a of (e.modelChanges?.added || [])) { live.add(a); retired.delete(a) }
    for (const r of (e.modelChanges?.removed || [])) { live.delete(r); retired.add(r) }
  }
  return { chrono: chrono.reverse(), live: [...live].sort(), retired: [...retired].sort() }
}

export function formatCommentHtml (text) {
  if (!text) return ''
  const clean = text.replace(/[\u{1F300}-\u{1FAFF}]/gu, '')
  const escaped = esc(clean)
  const withCodeBlocks = escaped.replace(/```([a-z0-9_-]*)\n([\s\S]*?)```/g, (_, lang, code) =>
    `<pre class="pr-code-block"><code>${code}</code></pre>`
  )
  const withInlineCode = withCodeBlocks.replace(/`([^`\n]+)`/g, '<code>$1</code>')
  const parts = withInlineCode.split(/(<pre[\s\S]*?<\/pre>)/g)
  return parts.map((part, i) => i % 2 === 1 ? part : part.replace(/\n\n+/g, '<br><br>').replace(/\n/g, '<br>')).join('')
}

