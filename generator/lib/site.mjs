function renderDiff(container, text, label, ghUrl, mode) {
  mode = mode || 'unified';
  container.dataset.raw = text;
  const lines = text.split(/\\r?\\n/);
  const frag = document.createDocumentFragment();

  const toolbar = document.createElement('div');
  toolbar.className = 'diff-toolbar';
  toolbar.innerHTML = '<span class="diff-toolbar-title">$ git diff ' + label.slice(0, 12) + '^!</span>';

  const actions = document.createElement('div');
  actions.className = 'diff-toolbar-actions';

  const copyBtn = document.createElement('button');
  copyBtn.className = 'diff-copy-btn';
  copyBtn.textContent = '[copy diff]';
  copyBtn.onclick = () => copyDiff(copyBtn);
  actions.appendChild(copyBtn);

  if (ghUrl) {
    const ghLink = document.createElement('a');
    ghLink.className = 'diff-gh-btn';
    ghLink.href = ghUrl;
    ghLink.target = '_blank';
    ghLink.rel = 'noopener';
    ghLink.textContent = '[github]';
    actions.appendChild(ghLink);
  }

  toolbar.appendChild(actions);
  frag.appendChild(toolbar);

  if (mode === 'split') {
    // Before/after columns: pair runs of - lines with following + runs.
    const table = document.createElement('table');
    table.className = 'diff-split';
    const addCell = (tr, cls, txt) => {
      const td = document.createElement('td');
      td.className = 'diff-cell ' + cls;
      td.textContent = txt;
      tr.appendChild(td);
    };
    let i = 0;
    while (i < lines.length) {
      const line = lines[i];
      if (line.startsWith('diff --git') || line.startsWith('index ') || line.startsWith('@@') || line.startsWith('+++') || line.startsWith('---')) {
        const tr = document.createElement('tr');
        const td = document.createElement('td');
        td.colSpan = 2;
        td.className = 'diff-cell diff-hdr';
        td.textContent = line;
        tr.appendChild(td);
        table.appendChild(tr);
        i++;
        continue;
      }
      if (line.startsWith('-') && !line.startsWith('---')) {
        const dels = [];
        while (i < lines.length && lines[i].startsWith('-') && !lines[i].startsWith('---')) { dels.push(lines[i].slice(1)); i++; }
        const adds = [];
        while (i < lines.length && lines[i].startsWith('+') && !lines[i].startsWith('+++')) { adds.push(lines[i].slice(1)); i++; }
        const n = Math.max(dels.length, adds.length);
        for (let k = 0; k < n; k++) {
          const tr = document.createElement('tr');
          addCell(tr, 'diff-del', dels[k] ?? '');
          addCell(tr, 'diff-add', adds[k] ?? '');
          table.appendChild(tr);
        }
        continue;
      }
      if (line.startsWith('+') && !line.startsWith('+++')) {
        const tr = document.createElement('tr');
        addCell(tr, 'diff-del', '');
        addCell(tr, 'diff-add', line.slice(1));
        table.appendChild(tr);
        i++;
        continue;
      }
      const tr = document.createElement('tr');
      const ctx = line.startsWith(' ') ? line.slice(1) : line;
      addCell(tr, 'diff-ctx', ctx);
      addCell(tr, 'diff-ctx', ctx);
      table.appendChild(tr);
      i++;
    }
    frag.appendChild(table);
    container.innerHTML = '';
    container.appendChild(frag);
    return;
  }

  const pre = document.createElement('pre');
  pre.className = 'diff-pre';
  for (const line of lines) {
    const row = document.createElement('div');
    row.className = 'diff-line';
    const marker = document.createElement('span');
    marker.className = 'diff-marker';
    const textSpan = document.createElement('span');
    textSpan.className = 'diff-text';
    
    if (line.startsWith('+++') || line.startsWith('---') || line.startsWith('diff --git') || line.startsWith('index ')) {
      row.classList.add('diff-hdr');
      marker.textContent = ' ';
      textSpan.textContent = line;
    } else if (line.startsWith('+')) {
      row.classList.add('diff-add');
      marker.textContent = '+';
      textSpan.textContent = line.slice(1);
    } else if (line.startsWith('-')) {
      row.classList.add('diff-del');
      marker.textContent = '−';
      textSpan.textContent = line.slice(1);
    } else if (line.startsWith('@@')) {
      row.classList.add('diff-hunk');
      marker.textContent = ' ';
      textSpan.textContent = line;
    } else {
      marker.textContent = ' ';
      textSpan.textContent = line.startsWith(' ') ? line.slice(1) : line;
    }
    row.appendChild(marker);
    row.appendChild(textSpan);
    pre.appendChild(row);
  }
  frag.appendChild(pre);

  container.innerHTML = '';
  container.appendChild(frag);
}
